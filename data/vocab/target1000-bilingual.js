export function buildBilingualIdiomBank(entries){
  if(!Array.isArray(entries))return [];
  const seen=new Set();
  return entries.flatMap(row=>{
    const no=Number(row?.no),phrase=String(row?.en||'').trim();
    const meaning=String(row?.ja||IDIOM_GLOSSES[no]||'').trim();
    const id=String(row?.id||'');
    if(!phrase||!meaning||!/^t1000_\d{4}$/.test(id)||seen.has(id))return [];
    seen.add(id);
    return [{id,phrase,meaning}];
  });
}
